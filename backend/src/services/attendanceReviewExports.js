// ── Word ─────────────────────────────────────────────────────────────────

const F = 'Arial';
const tr = (s, o = {}) => new TextRun({ text: String(s), font: F, size: o.size || 21, bold: o.bold, italics: o.it, color: o.color });
const para = (runs, o = {}) => new Paragraph({ children: Array.isArray(runs) ? runs : [tr(runs, o)], alignment: o.align, spacing: { after: o.after ?? 120, before: o.before ?? 0 } });
const BORDER = { style: BorderStyle.SINGLE, size: 4, color: 'BFBFBF' };
const NONE = { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' };
const cell = (s, w, o = {}) => new TableCell({
  width: { size: w, type: WidthType.DXA }, shading: o.fill ? { type: ShadingType.CLEAR, fill: o.fill, color: 'auto' } : undefined,
  margins: { top: o.tight ? 15 : 40, bottom: o.tight ? 15 : 40, left: 70, right: 70 }, borders: { top: BORDER, bottom: BORDER, left: BORDER, right: BORDER },
  children: [new Paragraph({ alignment: o.align, children: [tr(s, { size: o.size || 17, bold: o.bold, color: o.color })] })],
});
function table(heads, rows, widths, size, tight) {
  return new Table({
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA }, columnWidths: widths,
    rows: [
      new TableRow({ tableHeader: true, children: heads.map((h, i) => cell(h, widths[i], { bold: true, fill: '1F3864', color: 'FFFFFF', size, tight })) }),
      ...rows.map((r) => new TableRow({ cantSplit: true, children: r.map((v, i) => cell(v?.v ?? v ?? '', widths[i], { fill: v?.fill, align: v?.align, bold: v?.bold, size, tight })) })),
    ],
  });
}
const C = AlignmentType.CENTER; const R = AlignmentType.RIGHT;

function signature() {
  const side = (txt, align) => new TableCell({ width: { size: 4500, type: WidthType.DXA }, borders: { top: NONE, bottom: NONE, left: NONE, right: NONE },
    children: [para('______________________', { after: 40, align }), para([tr(txt, { bold: true })], { after: 0, align })] });
  return [para('', { after: 500 }), new Table({ width: { size: 9000, type: WidthType.DXA }, columnWidths: [4500, 4500],
    rows: [new TableRow({ children: [side('HR Manager'), side('Received by employee (signature & date)', R)] })] })];
}

