const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const MON3 = MONTHS.map((m) => m.slice(0, 3).toUpperCase());
const inr = (n) => `₹${Math.round(Number(n) || 0).toLocaleString('en-IN')}`;
const days = (d) => (d === 1 ? '1 day' : `${d} days`);
const hm = (min) => { const m = Math.round(Number(min) || 0); return m >= 60 ? `${Math.floor(m / 60)} h${m % 60 ? ` ${m % 60} min` : ''}` : `${m} min`; };
const people = (n) => (n === 1 ? '1 person' : `${n} people`);
// Names in the master sometimes carry trailing digits or doubled spaces; notes and notices show them clean.
const cleanName = (n) => String(n || '').replace(/[\d\s]+$/, '').replace(/\s+/g, ' ').trim();
const fmtDay = (iso) => { const d = new Date(`${iso}T00:00:00Z`); return `${d.getUTCDate()} ${MONTHS[d.getUTCMonth()].slice(0, 3)}`; };
function todayIst(now = new Date()) {
  return now.toLocaleDateString('en-IN', { timeZone: 'Asia/Kolkata', day: 'numeric', month: 'long', year: 'numeric' });
}
function monthLabel(result) { const { month, year } = result.meta; return `${MONTHS[month - 1]} ${year}`; }
function prevLabel(result) { const [y, m] = result.meta.prev_ym.split('-').map(Number); return `${MONTHS[m - 1]} ${y}`; }
const fileStem = (result) => `${MONTHS[result.meta.month - 1].slice(0, 3)}${result.meta.year}`;

// ── Excel ────────────────────────────────────────────────────────────────

function sheet(rows, cols) {
  const aoa = [cols.map((c) => c.h), ...rows.map((r) => cols.map((c) => { const v = c.v ? c.v(r) : r[c.k]; return v === undefined || v === null ? '' : v; }))];
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  ws['!cols'] = cols.map((c) => ({ wch: c.w || Math.max(10, c.h.length + 2) }));
  ws['!autofilter'] = { ref: XLSX.utils.encode_range({ s: { r: 0, c: 0 }, e: { r: Math.max(aoa.length - 1, 0), c: cols.length - 1 } }) };
  return ws;
}

